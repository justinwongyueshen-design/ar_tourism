<?php
/**
 * One-time installer: creates the database tables, demo data and the first administrator.
 * DELETE the install/ folder when you are done.
 */
declare(strict_types=1);
require_once __DIR__ . '/../includes/bootstrap.php';

$lockFile = __DIR__ . '/.lock';
$locked = is_file($lockFile);
$errors = [];
$done = false;
$configWritten = false;
$configSnippet = '';

$val = static fn(string $k, string $d = ''): string => is_post() ? input($k, $d) : $d;

if (!$locked && is_post()) {
    csrf_require();
    $host = input('db_host', 'localhost');
    $port = input('db_port', '3306');
    $name = input('db_name');
    $user = input('db_user');
    $pass = (string) ($_POST['db_pass'] ?? '');
    $adminUser = input('admin_user');
    $adminEmail = input('admin_email');
    $adminPass = (string) ($_POST['admin_pass'] ?? '');
    $demo = isset($_POST['demo']);

    if (!preg_match('/^[A-Za-z0-9_]{1,64}$/', $name)) { $errors[] = 'Database name may only contain letters, numbers and underscores.'; }
    if (!preg_match('/^\d{1,5}$/', $port)) { $errors[] = 'Invalid port.'; }
    if (!preg_match('/^[A-Za-z0-9_.-]{3,50}$/', $adminUser)) { $errors[] = 'Admin username: 3-50 letters, numbers, dot, dash or underscore.'; }
    if (!filter_var($adminEmail, FILTER_VALIDATE_EMAIL)) { $errors[] = 'Enter a valid admin email.'; }
    if (strlen($adminPass) < 10) { $errors[] = 'Admin password must be at least 10 characters.'; }

    if (!$errors) {
        try {
            $pdo = new PDO("mysql:host=$host;port=$port;charset=utf8mb4", $user, $pass, [PDO::ATTR_ERRMODE => PDO::ERRMODE_EXCEPTION]);
            try { $pdo->exec("CREATE DATABASE IF NOT EXISTS `$name` CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci"); } catch (Throwable $e) { /* shared hosting: database already exists */ }
            $pdo->exec("USE `$name`");

            $sql = (string) file_get_contents(APP_ROOT . '/database/database.sql');
            if (!$demo) {   // strip the demo-data section
                $sql = explode('-- =====================  DEMO DATA', $sql)[0];
            }
            $lines = array_filter(explode("\n", $sql), static fn($l) => !str_starts_with(ltrim($l), '--'));
            foreach (preg_split('/;\s*\n/', implode("\n", $lines)) ?: [] as $stmt) {
                if (trim($stmt) !== '') { $pdo->exec($stmt); }
            }
            if (!$demo) {   // minimal settings so the site renders
                $pdo->exec("INSERT IGNORE INTO settings (setting_key, setting_value) VALUES ('site_name','AR Tourism Explorer'),('tagline','Point. Scan. Discover.'),('hero_title','Discover heritage through your camera'),('hero_subtitle','Scan a tourism poster and watch attractions come alive.'),('ar_filter_min_cf','0.001'),('ar_filter_beta','1000')");
            }
            $exists = $pdo->prepare('SELECT id FROM users WHERE username = ? OR email = ?');
            $exists->execute([$adminUser, $adminEmail]);
            if ($exists->fetch()) {
                $errors[] = 'That admin username or email already exists in the database.';
            } else {
                $ins = $pdo->prepare("INSERT INTO users (username, email, full_name, role, status, password_hash) VALUES (?, ?, 'Administrator', 'admin', 'active', ?)");
                $ins->execute([$adminUser, $adminEmail, password_hash($adminPass, PASSWORD_DEFAULT)]);

                $configSnippet = "<?php\n// Generated by install/index.php\ndefine('DB_HOST', " . var_export($host, true) . ");\ndefine('DB_PORT', " . var_export($port, true) . ");\ndefine('DB_NAME', " . var_export($name, true) . ");\ndefine('DB_USER', " . var_export($user, true) . ");\ndefine('DB_PASS', " . var_export($pass, true) . ");\n";
                $configFile = APP_ROOT . '/includes/config.local.php';
                $configWritten = !is_file($configFile) && @file_put_contents($configFile, $configSnippet, LOCK_EX) !== false;
                if ($configWritten) { @chmod($configFile, 0640); }
                @file_put_contents($lockFile, date('c'));
                $done = true;
            }
        } catch (Throwable $e) {
            $errors[] = 'Database error: ' . $e->getMessage();
        }
    }
}
$checks = [
    'PHP 8.1 or newer'            => version_compare(PHP_VERSION, '8.1.0', '>='),
    'PDO MySQL extension'         => extension_loaded('pdo_mysql'),
    'Fileinfo extension'          => extension_loaded('fileinfo'),
    'GD extension (image resize)' => extension_loaded('gd'),
    'assets/uploads writable'     => is_writable(APP_ROOT . '/assets/uploads'),
    'assets/ar-targets writable'  => is_writable(APP_ROOT . '/assets/ar-targets'),
];
?><!DOCTYPE html>
<html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1"><meta name="robots" content="noindex">
<title>Installer · <?= e(APP_NAME) ?></title>
<link rel="stylesheet" href="https://cdn.jsdelivr.net/npm/bootstrap@<?= e(BOOTSTRAP_VERSION) ?>/dist/css/bootstrap.min.css">
</head><body class="bg-light"><main class="container py-5" style="max-width:760px">
<h1 class="h3 mb-4">AR Tourism Explorer — Installer</h1>
<?php if ($locked && !$done): ?>
  <div class="alert alert-warning">The installer has already been run. For safety, <strong>delete the <code>install/</code> folder</strong> from the server. To run it again, delete <code>install/.lock</code> first.</div>
<?php elseif ($done): ?>
  <div class="alert alert-success"><h2 class="h5">Installation complete</h2>
    <?php if ($configWritten): ?><p class="mb-2">Database settings were saved to <code>includes/config.local.php</code>.</p>
    <?php else: ?><p class="mb-2">Could not write <code>includes/config.local.php</code> automatically. Create it with this content:</p><pre class="bg-white p-2 border rounded small"><?= e($configSnippet) ?></pre><?php endif; ?>
    <p class="mb-2"><strong>Now delete the <code>install/</code> folder.</strong></p>
    <a class="btn btn-success" href="<?= e(url('admin/login.php')) ?>">Go to admin login</a> <a class="btn btn-outline-secondary" href="<?= e(url('index.php')) ?>">View website</a></div>
<?php else: ?>
  <div class="card mb-4"><div class="card-header">Server check</div><ul class="list-group list-group-flush">
    <?php foreach ($checks as $label => $ok): ?><li class="list-group-item d-flex justify-content-between"><?= e($label) ?><span class="badge text-bg-<?= $ok ? 'success' : 'danger' ?>"><?= $ok ? 'OK' : 'Problem' ?></span></li><?php endforeach; ?>
  </ul></div>
  <?php if (!is_secure_context_server()): ?><div class="alert alert-warning small">You are not on HTTPS. Installing is fine, but phones need HTTPS (or localhost) to open the camera.</div><?php endif; ?>
  <?php foreach ($errors as $err): ?><div class="alert alert-danger"><?= e($err) ?></div><?php endforeach; ?>
  <form method="post" class="card card-body" novalidate><?= csrf_field() ?>
    <h2 class="h5">Database</h2>
    <div class="row g-3 mb-4">
      <div class="col-md-8"><label class="form-label" for="db_host">Host</label><input class="form-control" id="db_host" name="db_host" value="<?= e($val('db_host', DB_HOST)) ?>"></div>
      <div class="col-md-4"><label class="form-label" for="db_port">Port</label><input class="form-control" id="db_port" name="db_port" value="<?= e($val('db_port', DB_PORT)) ?>"></div>
      <div class="col-md-4"><label class="form-label" for="db_name">Database name</label><input class="form-control" id="db_name" name="db_name" value="<?= e($val('db_name', DB_NAME)) ?>"></div>
      <div class="col-md-4"><label class="form-label" for="db_user">User</label><input class="form-control" id="db_user" name="db_user" value="<?= e($val('db_user', DB_USER)) ?>"></div>
      <div class="col-md-4"><label class="form-label" for="db_pass">Password</label><input class="form-control" type="password" id="db_pass" name="db_pass" autocomplete="off"></div>
    </div>
    <h2 class="h5">Administrator account</h2>
    <div class="row g-3 mb-4">
      <div class="col-md-6"><label class="form-label" for="admin_user">Username</label><input class="form-control" id="admin_user" name="admin_user" value="<?= e($val('admin_user', 'admin')) ?>" autocomplete="off"></div>
      <div class="col-md-6"><label class="form-label" for="admin_email">Email</label><input class="form-control" type="email" id="admin_email" name="admin_email" value="<?= e($val('admin_email')) ?>"></div>
      <div class="col-12"><label class="form-label" for="admin_pass">Password (min. 10 characters)</label><input class="form-control" type="password" id="admin_pass" name="admin_pass" autocomplete="new-password"></div>
    </div>
    <div class="form-check mb-4"><input class="form-check-input" type="checkbox" id="demo" name="demo" <?= (!is_post() || isset($_POST['demo'])) ? 'checked' : '' ?>><label class="form-check-label" for="demo">Include demo data (destinations, attractions and a demo AR poster)</label></div>
    <button class="btn btn-success btn-lg" type="submit">Install</button>
  </form>
<?php endif; ?>
</main></body></html>
